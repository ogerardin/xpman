#!/bin/bash
# Generate sonar-project.properties with Maven-resolved dependencies

set -e

# Check prerequisites
if ! command -v sonar-scanner &> /dev/null; then
    echo "Error: sonar-scanner not installed. Run: brew install sonar-scanner"
    exit 1
fi

if [ -z "$SONAR_TOKEN" ]; then
    echo "Error: SONAR_TOKEN not set"
    echo "Generate a token at http://localhost:9000/account/security"
    exit 1
fi

# Build the project first
echo "Building project..."
mvn -B -DskipTests clean package

# Use reactor to get all dependencies
echo "Resolving dependencies..."
ALL_CP=$(mvn dependency:list -DoutputAbsoluteArtifactFilename=true 2>&1 | \
    grep "The following files have been resolved" -A 100 | \
    grep "\.jar" | sed 's/.*:\(.*\.jar\).*/\1/' | tr '\n' ',' | sed 's/,$//')

# Generate sonar-project.properties
cat > sonar-project.properties <<EOF
# Auto-generated by generate-sonar-properties.sh
# Do not edit manually

sonar.projectKey=com.ogerardin.xplane:xpman
sonar.projectName=XPman
sonar.projectVersion=1.0
sonar.sourceEncoding=UTF-8
sonar.java.source=25

# Source and test directories
sonar.sources=xpman-api/src/main/java,xpman-fx/src/main/java
sonar.tests=xpman-api/src/test/java,xpman-fx/src/test/java

# Compiled classes
sonar.java.binaries=xpman-api/target/classes,xpman-fx/target/classes
sonar.java.test.binaries=xpman-api/target/test-classes,xpman-fx/target/test-classes

# Production dependencies (resolved from Maven reactor)
sonar.java.libraries=xpman-api/target/xpman-api-0.0.0-DEV.jar,xpman-fx/target/xpman-fx-0.0.0-DEV.jar,${ALL_CP}

# Test dependencies (same as production + test frameworks)
sonar.java.test.libraries=xpman-api/target/xpman-api-0.0.0-DEV.jar,xpman-fx/target/xpman-fx-0.0.0-DEV.jar,${ALL_CP}
EOF

echo "Generated sonar-project.properties"
echo ""
echo "Running SonarQube analysis..."
sonar-scanner -Dsonar.host.url=http://localhost:9000 -Dsonar.token=$SONAR_TOKEN

echo ""
echo "Analysis complete. View results at:"
echo "http://localhost:9000/dashboard?id=com.ogerardin.xplane:xpman"
